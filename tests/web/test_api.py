    def test_24_upload_resource_limits(self):
        pid = self.project()
        base = {"base_revision": 0, "bytes": len(self.fixture), "parts": 1,
                "sha256": hashlib.sha256(self.fixture).hexdigest(), "title": "Bounds", "width": 64, "height": 48}
        for change in [{"bytes": 0}, {"bytes": 104857601}, {"parts": 0}, {"parts": 2},
                       {"width": 0}, {"width": 16385}, {"width": 9000, "height": 9000}, {"sha256": "g"*64}]:
            with self.subTest(change=change):
                self.req(self.owner, "POST", f"/api/projects/{pid}/uploads", status=400, json={**base, **change})
        for _ in range(5):
            self.begin(pid)
        self.req(self.owner, "POST", f"/api/projects/{pid}/uploads", status=400, json=base)

    def test_25_expired_sessions_and_uploads(self):
        pid = self.project()
        uid = self.begin(pid)
        self.db.execute("UPDATE photocraft.uploads SET created_at=now()-interval '2 days' WHERE id=%s", (uid,))
        # A new upload runs bounded expiry cleanup, so stale bytes cannot accumulate forever.
        self.begin(pid)
        self.req(self.owner, "PUT", f"/api/uploads/{uid}/0", status=404, data=self.fixture)
        session = requests.Session()
        session.trust_env = False
        session.headers['Origin'] = BASE
        token = secrets.token_hex(32)
        session.cookies.set('pc_session', token)
        self.db.execute("INSERT INTO photocraft.sessions(hash,account_id,expires_at) VALUES(%s,%s,now()-interval '1 minute')",
                        (hashlib.sha256(token.encode()).hexdigest(), self.accounts[0][0]))
        self.req(session, "GET", "/api/me", status=401)

    def test_26_preview_size_and_access(self):
        from PIL import Image
        pid = self.project()
        f = io.BytesIO()
        Image.new('RGB', (320, 240), '#805bdf').save(f, format='PNG')
        self.req(self.owner, 'PUT', f'/api/projects/{pid}/thumbnail', data=f.getvalue())
        self.assertEqual(self.req(self.owner, 'GET', f'/api/projects/{pid}/thumbnail').content, f.getvalue())
        self.member(pid, 2, 'view')
        self.req(self.viewer, 'PUT', f'/api/projects/{pid}/thumbnail', status=404, data=f.getvalue())
        for data in [b'bad', f.getvalue()[:20], f.getvalue()[:16] + (100000).to_bytes(4, 'big') + f.getvalue()[20:]]:
            self.req(self.owner, 'PUT', f'/api/projects/{pid}/thumbnail', status=400, data=data)

    def test_27_member_validation_and_owner_protection(self):
        pid = self.project()
        for email, role in [('bad', 'edit'), (self.accounts[1][1], 'admin')]:
            self.req(self.owner, 'PUT', f'/api/projects/{pid}/members', status=400, json={'email': email, 'role': role})
        self.req(self.owner, 'PUT', f'/api/projects/{pid}/members', json={'email': self.accounts[0][1], 'role': 'view'})
        self.assertEqual(self.req(self.owner, 'GET', f'/api/projects/{pid}').json()['role'], 'owner')

    def test_28_large_request_rejected(self):
        pid = self.project()
        uid = self.begin(pid)
        self.req(self.owner, 'PUT', f'/api/uploads/{uid}/0', status=413, data=b'x'*(CHUNK+1025))

    def test_29_static_cache_and_download_headers(self):
        import re
        index = self.req(self.anon, 'GET', '/')
        self.assertEqual(index.headers['Cache-Control'], 'no-cache')
        wasm = re.search(r'photocraft-web-[a-z0-9]+_bg\.wasm', index.text)
        self.assertIsNotNone(wasm)
        response = self.req(self.anon, 'HEAD', '/'+wasm.group())
        self.assertIn('immutable', response.headers['Cache-Control'])
        self.assertEqual(response.headers['Content-Type'], 'application/wasm')


